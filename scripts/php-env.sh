#!/usr/bin/env bash
#
# Shared setup for the local PHP backend. Sourced, not run.
#
# The handlers need four things a plain `vite` does not provide: PHP, a config
# with a secret, a writable directory for the counters and the guestbook, and a
# mailer that captures instead of sending. This puts all four in one place so
# scripts/dev.sh and scripts/php-test.sh cannot drift apart in how they set the
# backend up — the sort of difference that makes a suite pass while the browser
# fails, or the other way about.
#
# Everything it creates lives under frontend/.php-dev/, which is gitignored and
# can be deleted at any time; it is rebuilt on the next run.

# shellcheck disable=SC2034  # these are for the sourcing script

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PUBLIC_DIR="$ROOT/frontend/public"
DEV_ROOT="$ROOT/frontend/.php-dev"

# The handler files, which is everything a web root needs to serve the API. The
# test run copies these into a root of its own rather than symlinking them: PHP
# resolves __DIR__ through a symlink to the real file's directory, so a
# symlinked contact.php would read the *dev* config and write to the dev
# guestbook — isolation that silently is not.
PHP_FILES=(
    form-lib.php
    contact.php
    guestbook.php
    guestbook-moderate.php
    contact-messages.json
    guestbook-messages.json
)

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

# php_env_write_config <path> <rate_dir> <guestbook_dir> <site_url> [secret]
#
# Paths are written absolute. They are read at request time by a server whose
# working directory is not ours, and a relative path that resolves differently
# in the two is a bad afternoon.
php_env_write_config() {
    local path="$1" rate_dir="$2" gb_dir="$3" site_url="$4"
    local secret="${5:-$(php -r 'echo bin2hex(random_bytes(32));')}"

    cat > "$path" <<EOF
<?php
/**
 * LOCAL DEV ONLY. Gitignored, generated by scripts/php-env.sh, and not the real
 * configuration — delete it and it is written again on the next run.
 *
 * The real one is uploaded to the server by hand and left there. See
 * contact-config.example.php for what every key means.
 */
declare(strict_types=1);

if (!defined('CONTACT_APP')) {
    http_response_code(403);
    exit;
}

return [
    'to' => 'dev@localhost',
    'from' => 'Website Contact <no-reply@localhost>',
    'secret' => '$secret',

    // Under frontend/.php-dev/, which is gitignored. On the server these have to
    // be somewhere a deploy does not overwrite — see contact-config.example.php.
    'rate_dir' => '$rate_dir',
    'guestbook_dir' => '$gb_dir',

    // Where the guestbook's delete links point. The Vite dev server, since that
    // is where you are looking at the app — the link then goes through the same
    // proxy the app's own requests do.
    'site_url' => '$site_url',

    'guestbook_enabled' => true,
    'enabled' => true,
];
EOF
}

# An existing config may predate the guestbook. Say so plainly rather than
# letting the tab report itself unconfigured with no clue why.
php_env_check_config() {
    local path="$1"
    local gb
    gb="$(php -r '
        define("CONTACT_APP", true);
        $c = require $argv[1];
        echo is_array($c) ? (string) ($c["guestbook_dir"] ?? "") : "";
    ' "$path" 2>/dev/null)"

    if [ -z "$gb" ]; then
        echo
        echo "  !  $path has no 'guestbook_dir'."
        echo "     The guestbook tab will report itself unconfigured. Add:"
        echo
        echo "       'guestbook_dir' => '$DEV_ROOT/data',"
        echo
    fi
}

# Where the handlers are actually reading and writing, resolved from the config
# rather than assumed — so the two can never disagree in the output.
php_env_report() {
    local path="$1" mail_log="$2"
    php -r '
        define("CONTACT_APP", true);
        $c = require $argv[1];
        $dir = fn($k) => ($c[$k] ?? null) ? (realpath($c[$k]) ?: $c[$k]) : "(unset)";
        printf("  entries   %s\n", $dir("guestbook_dir"));
        printf("  counters  %s\n", $dir("rate_dir"));
        printf("  mail to   %s\n", $c["to"] ?? "(unset)");
    ' "$path" 2>/dev/null || true
    echo "  mail log  $mail_log"
}

# ---------------------------------------------------------------------------
# The capturing mailer
# ---------------------------------------------------------------------------

# php_env_write_sendmail <path> <log>
#
# mail() hands the whole message — headers and body — to this on stdin, so the
# log is exactly what would have been sent. That matters more than it sounds for
# the guestbook: the delete link exists nowhere else, so a stub that discarded
# the message would leave moderation with no way to be reached or tested.
php_env_write_sendmail() {
    local path="$1" log="$2"
    cat > "$path" <<EOF
#!/bin/sh
{
  echo "----- \$(date -u +%Y-%m-%dT%H:%M:%SZ) -----"
  cat
  echo
} >> "$log"
EOF
    chmod +x "$path"
}

# ---------------------------------------------------------------------------
# The server
# ---------------------------------------------------------------------------

# php -S prints "Address already in use" and exits, but by then the caller has
# already announced a port — so requests quietly go to whatever was listening,
# with the previous config and the previous maildir, and nothing points at
# either. Refuse instead.
php_env_require_port() {
    local port="$1"
    if lsof -nP -iTCP:"$port" -sTCP:LISTEN >/dev/null 2>&1; then
        echo "port $port is already in use — stop that server first:" >&2
        lsof -nP -iTCP:"$port" -sTCP:LISTEN >&2
        return 1
    fi
}

# php_env_stop <pid> <port>
#
# Killing the pid alone is not enough. PHP_CLI_SERVER_WORKERS makes php -S fork
# workers, and they do not go with the parent — they keep the socket, so the
# next run is refused the port with a list of processes nothing appears to own.
# Kill the parent, then anything still holding the port.
php_env_stop() {
    local pid="${1:-}" port="${2:-}"
    [ -n "$pid" ] && kill "$pid" 2>/dev/null || true

    if [ -n "$port" ]; then
        local strays
        strays="$(lsof -nP -iTCP:"$port" -sTCP:LISTEN -t 2>/dev/null || true)"
        # shellcheck disable=SC2086  # deliberately word-split: one pid per line
        [ -n "$strays" ] && kill $strays 2>/dev/null || true
    fi
    return 0
}

# php_env_serve <port> <doc_root> <sendmail> <log_file>
#
# Sets PHP_PID. Binds 127.0.0.1 explicitly: binding to :: makes `curl localhost`
# succeed while a browser fails, which is a miserable hour.
#
# PHP_CLI_SERVER_WORKERS is not optional. php -S is serial by default, and the
# locking the rate limits depend on is never actually contended without it — so
# the concurrency checks pass whatever the code does.
php_env_serve() {
    local port="$1" doc_root="$2" sendmail="$3" log="$4"

    PHP_CLI_SERVER_WORKERS=8 php \
        -d sendmail_path="$sendmail" \
        -d display_errors=0 \
        -S "127.0.0.1:$port" \
        -t "$doc_root" >"$log" 2>&1 &
    PHP_PID=$!

    # Wait for it to answer rather than sleeping a fixed guess
    local n=0
    until curl -fsS -o /dev/null "http://127.0.0.1:$port/contact.php" 2>/dev/null; do
        n=$((n + 1))
        if [ "$n" -gt 80 ] || ! kill -0 "$PHP_PID" 2>/dev/null; then
            echo "the PHP server did not start — see $log" >&2
            cat "$log" >&2
            return 1
        fi
        sleep 0.25
    done
}
